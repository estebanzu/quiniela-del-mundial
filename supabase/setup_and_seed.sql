CREATE OR REPLACE FUNCTION public.seed_dummies_and_predictions()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  dummy_usernames text[] := array['dummy_juan', 'dummy_sofia', 'dummy_diego', 'dummy_lucia', 'dummy_carlos'];
  d_username text;
  d_email text;
  d_id uuid;
  m_record record;
  p_home int;
  p_away int;
  created_count int := 0;
  pred_count int := 0;
BEGIN
  IF auth.jwt() ->> 'email' != 'admin@quiniela.local' THEN
    RAISE EXCEPTION 'Acceso denegado. Solo administradores.';
  END IF;

  PERFORM set_config('my.seeding_mode', 'on', true);

  FOREACH d_username in array dummy_usernames LOOP
    d_email := d_username || '@quiniela.local';
    
    SELECT id INTO d_id FROM auth.users where email = d_email;
    
    IF d_id IS NULL THEN
      d_id := gen_random_uuid();
      
      INSERT INTO auth.users (
        id,
        instance_id,
        email,
        encrypted_password,
        email_confirmed_at,
        raw_app_meta_data,
        raw_user_meta_data,
        created_at,
        updated_at,
        role,
        aud,
        confirmation_token
      )
      VALUES (
        d_id,
        '00000000-0000-0000-0000-000000000000',
        d_email,
        crypt('password123', gen_salt('bf')),
        now(),
        '{"provider":"email","providers":["email"]}',
        '{}',
        now(),
        now(),
        'authenticated',
        'authenticated',
        ''
      );
      
      created_count := created_count + 1;
    END IF;

    DELETE FROM public.predictions where user_id = d_id;

    FOR m_record in SELECT id, status, home_score, away_score FROM public.matches LOOP
      p_home := floor(random() * 5);
      p_away := floor(random() * 5);
      
      INSERT INTO public.predictions (user_id, match_id, predicted_home, predicted_away, points)
      VALUES (
        d_id, 
        m_record.id, 
        p_home, 
        p_away,
        CASE
          WHEN m_record.status = 'finished' THEN
            CASE
              WHEN m_record.home_score = p_home AND m_record.away_score = p_away THEN 5
              WHEN sign(m_record.home_score - m_record.away_score) = sign(p_home - p_away) THEN
                CASE
                  WHEN m_record.home_score = m_record.away_score then 1
                  ELSE 3
                END
              ELSE 0
            END
          ELSE 0
        END
      );
      
      pred_count := pred_count + 1;
    END LOOP;
  END LOOP;

  RETURN '¡Se crearon/verificaron los 5 usuarios dummy con éxito! Se registraron ' || pred_count || ' pronósticos aleatorios en total.';
END;
$$;

CREATE OR REPLACE FUNCTION public.propagate_bracket()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  is_group_stage_done boolean;
  match_rec record;
  winner_name text;
  loser_name text;
  
  g_name text;
  g_idx int;
  standing_rec record;
  third_rec record;
  matched_match_id bigint;
BEGIN
  IF (new.status = 'finished' and old.status is distinct from 'finished' and new.id >= 73) or
     (new.status = 'finished' and (old.home_score is distinct from new.home_score or old.away_score is distinct from new.away_score) and new.id >= 73) then
     
    IF new.home_score > new.away_score THEN
      winner_name := new.home_team;
      loser_name := new.away_team;
    ELSIF new.away_score > new.home_score THEN
      winner_name := new.away_team;
      loser_name := new.home_team;
    ELSE
      winner_name := new.home_team;
      loser_name := new.away_team;
    END IF;

    UPDATE public.matches
    SET home_team = replace(home_team, 'Ganador Partido ' || new.id, winner_name),
        away_team = replace(away_team, 'Ganador Partido ' || new.id, winner_name)
    where home_team like '%Ganador Partido ' || new.id || '%'
       or away_team like '%Ganador Partido ' || new.id || '%';

    UPDATE public.matches
    SET home_team = replace(home_team, 'Perdedor Partido ' || new.id, loser_name),
        away_team = replace(away_team, 'Perdedor Partido ' || new.id, loser_name)
    where home_team like '%Perdedor Partido ' || new.id || '%'
       or away_team like '%Perdedor Partido ' || new.id || '%';
  END IF;

  IF (new.id <= 72 and new.status = 'finished') THEN
    SELECT count(*) = 0 INTO is_group_stage_done
    FROM public.matches
    where id <= 72 and status != 'finished';

    IF is_group_stage_done THEN
      CREATE TEMP TABLE IF NOT EXISTS group_standings (
        team text primary key,
        grp text,
        points int default 0,
        goal_diff int default 0,
        goals_for int default 0
      ) ON COMMIT DROP;
      
      TRUNCATE TABLE group_standings;

      INSERT INTO group_standings (team, grp)
      SELECT distinct home_team, stage_group
      FROM public.matches
      where id <= 72;

      FOR match_rec in SELECT home_team, away_team, home_score, away_score FROM public.matches where id <= 72 and status = 'finished' LOOP
        UPDATE group_standings
        SET goals_for = goals_for + match_rec.home_score,
            goal_diff = goal_diff + (match_rec.home_score - match_rec.away_score),
            points = points + CASE 
              WHEN match_rec.home_score > match_rec.away_score THEN 3
              WHEN match_rec.home_score = match_rec.away_score THEN 1
              ELSE 0
            END
        where team = match_rec.home_team;

        UPDATE group_standings
        SET goals_for = goals_for + match_rec.away_score,
            goal_diff = goal_diff + (match_rec.away_score - match_rec.home_score),
            points = points + CASE 
              WHEN match_rec.away_score > match_rec.home_score THEN 3
              WHEN match_rec.away_score = match_rec.home_score THEN 1
              ELSE 0
            END
        where team = match_rec.away_team;
      END LOOP;

      FOR g_name in SELECT distinct grp FROM group_standings LOOP
        g_idx := 1;
        FOR standing_rec in 
          SELECT team 
          FROM group_standings 
          where grp = g_name 
          ORDER BY points DESC, goal_diff DESC, goals_for DESC 
        LOOP
          IF g_idx = 1 THEN
            UPDATE public.matches
            SET home_team = replace(home_team, '1º ' || g_name, standing_rec.team),
                away_team = replace(away_team, '1º ' || g_name, standing_rec.team)
            where home_team like '%1º ' || g_name || '%' or away_team like '%1º ' || g_name || '%';
          ELSIF g_idx = 2 THEN
            UPDATE public.matches
            SET home_team = replace(home_team, '2º ' || g_name, standing_rec.team),
                away_team = replace(away_team, '2º ' || g_name, standing_rec.team)
            where home_team like '%2º ' || g_name || '%' or away_team like '%2º ' || g_name || '%';
          END IF;

          g_idx := g_idx + 1;
        END LOOP;
      END LOOP;

      CREATE TEMP TABLE IF NOT EXISTS third_places (
        team text primary key,
        grp text,
        points int,
        goal_diff int,
        goals_for int
      ) ON COMMIT DROP;

      TRUNCATE TABLE third_places;

      FOR g_name in SELECT distinct grp FROM group_standings LOOP
        INSERT INTO third_places (team, grp, points, goal_diff, goals_for)
        SELECT team, grp, points, goal_diff, goals_for
        FROM (
          SELECT team, grp, points, goal_diff, goals_for,
                 row_number() over (order by points desc, goal_diff desc, goals_for desc) as rank
          FROM group_standings
          where grp = g_name
        ) r
        where rank = 3;
      END LOOP;

      FOR third_rec in 
        SELECT team, grp 
        FROM third_places 
        ORDER BY points DESC, goal_diff DESC, goals_for DESC 
        LIMIT 8
      LOOP
        DECLARE
          group_letter text := split_part(third_rec.grp, ' ', 2);
        BEGIN
          SELECT id INTO matched_match_id
          FROM public.matches
          where id >= 73 and id <= 88
            and (
              (home_team like '3º Grupo%' and home_team like '%' || group_letter || '%') or
              (away_team like '3º Grupo%' and away_team like '%' || group_letter || '%')
            )
          ORDER BY id ASC
          LIMIT 1;

          IF matched_match_id IS NOT NULL THEN
            UPDATE public.matches
            SET home_team = CASE WHEN home_team like '3º Grupo%' and home_team like '%' || group_letter || '%' THEN third_rec.team ELSE home_team END,
                away_team = CASE WHEN away_team like '3º Grupo%' and away_team like '%' || group_letter || '%' THEN third_rec.team ELSE away_team END
            where id = matched_match_id;
          END IF;
        END;
      END LOOP;

    END IF;
  END IF;

  RETURN new;
END;
$$;

