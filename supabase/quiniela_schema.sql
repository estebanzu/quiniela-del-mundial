-- Quiniela Supabase schema and RLS policies

-- Matches Table
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  home_team text not null,
  away_team text not null,
  match_date timestamptz not null,
  home_score int,
  away_score int,
  status text not null default 'pending',
  score_manually_set boolean not null default false
);

-- Predictions Table
create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  match_id bigint not null references public.matches(id) on delete cascade,
  predicted_home int not null,
  predicted_away int not null,
  points int not null default 0,
  created_at timestamptz not null default now()
);

-- Ensure user can make only one prediction per match
create unique index if not exists predictions_user_match_unique on public.predictions (user_id, match_id);

-- Enable Row Level Security
alter table public.matches enable row level security;
alter table public.predictions enable row level security;

