-- Scoring Function: Calculates points when a match changes to 'finished' or when scores are corrected.
create or replace function public.update_prediction_points()
returns trigger
language plpgsql
security definer
as $$
declare
  pred_rec record;
  prev_rec record;
  base_pts int;
  streak int;
  final_pts int;
begin
  if (new.status = 'finished') and 
     (old.status is distinct from 'finished' or 
      old.home_score is distinct from new.home_score or 
      old.away_score is distinct from new.away_score) then
    
    for pred_rec in select * from public.predictions where match_id = new.id loop
      -- Calculate base points
      base_pts := case
        when new.home_score = pred_rec.predicted_home and new.away_score = pred_rec.predicted_away then 5
        when sign(new.home_score - new.away_score) = sign(pred_rec.predicted_home - pred_rec.predicted_away) then
          case when new.home_score = new.away_score then 1 else 3 end
        else 0
      end;

      -- If the user scored, check their streak on previous matches
      if base_pts > 0 then
        streak := 0;
        for prev_rec in
          select p.points
          from public.predictions p
          inner join public.matches m on m.id = p.match_id
          where p.user_id = pred_rec.user_id
            and m.status = 'finished'
            and m.match_date < new.match_date
          order by m.match_date desc
        loop
          if prev_rec.points > 0 then
            streak := streak + 1;
          else
            exit;
          end if;
        end loop;

        -- Apply x1.5 multiplier if streak >= 3 consecutive wins before this match
        if streak >= 3 then
          final_pts := ceil(base_pts * 1.5);
        else
          final_pts := base_pts;
        end if;
      else
        final_pts := 0;
      end if;

      update public.predictions set points = final_pts where id = pred_rec.id;
    end loop;

  elsif (new.status = 'pending' and old.status = 'finished') then
    update public.predictions p
    set points = 0
    where p.match_id = new.id;
  end if;

  return new;
end;
$$;

-- Trigger to execute scoring logic after a match is updated
drop trigger if exists trigger_update_prediction_points on public.matches;
create trigger trigger_update_prediction_points
after update on public.matches
for each row
execute procedure public.update_prediction_points();

-- Time Lock Function: Prevents users from inserting/updating predictions less than 1 hour before kickoff.
create or replace function public.check_prediction_lock()
returns trigger
language plpgsql
security definer
as $$
declare
  match_kickoff timestamptz;
begin
  -- Bypass lock checks during database seeding operations
  if current_setting('my.seeding_mode', true) = 'on' then
    return new;
  end if;

  -- For updates, only enforce the lock if the predicted scores are actually changing.
  -- This allows the system to update points, metadata, etc., even after kickoff.
  if (TG_OP = 'UPDATE') and 
     (old.predicted_home = new.predicted_home) and 
     (old.predicted_away = new.predicted_away) then
    return new;
  end if;

  select match_date into match_kickoff from public.matches where id = new.match_id;
  
  if match_kickoff is null then
    raise exception 'Match not found';
  end if;
  
  if now() >= match_kickoff - interval '5 minutes' then
    raise exception 'Predictions are locked for this match.';
  end if;
  
  return new;
end;
$$;

-- Trigger to enforce time lock check before creating or updating predictions
drop trigger if exists trigger_check_prediction_lock on public.predictions;
create trigger trigger_check_prediction_lock
before insert or update on public.predictions
for each row
execute procedure public.check_prediction_lock();

