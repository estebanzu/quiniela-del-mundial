-- 6. Logins Trigger Function
create or replace function public.trigger_check_login_badges()
returns trigger
language plpgsql
security definer
as $$
declare
  uid uuid;
  has_three_day boolean;
  has_seven_day boolean;
  has_fifteen_day boolean;
begin
  uid := NEW.user_id;

  -- 1. first_login
  if not exists (select 1 from public.user_badges where user_id = uid and badge_key = 'first_login') then
    perform public.award_badge(uid, 'first_login');
  end if;

  -- 2. three_days_streak
  if not exists (select 1 from public.user_badges where user_id = uid and badge_key = 'three_days_streak') then
    select count(*) = 3 into has_three_day
    from public.user_logins
    where user_id = uid
      and login_date >= NEW.login_date - 2
      and login_date <= NEW.login_date;
      
    if has_three_day then
      perform public.award_badge(uid, 'three_days_streak');
    end if;
  end if;

  -- 3. seven_days_streak
  if not exists (select 1 from public.user_badges where user_id = uid and badge_key = 'seven_days_streak') then
    select count(*) = 7 into has_seven_day
    from public.user_logins
    where user_id = uid
      and login_date >= NEW.login_date - 6
      and login_date <= NEW.login_date;
      
    if has_seven_day then
      perform public.award_badge(uid, 'seven_days_streak');
    end if;
  end if;

  -- 4. fifteen_days_streak
  if not exists (select 1 from public.user_badges where user_id = uid and badge_key = 'fifteen_days_streak') then
    select count(*) = 15 into has_fifteen_day
    from public.user_logins
    where user_id = uid
      and login_date >= NEW.login_date - 14
      and login_date <= NEW.login_date;
      
    if has_fifteen_day then
      perform public.award_badge(uid, 'fifteen_days_streak');
    end if;
  end if;

  -- 5. final_day_login (logged in on July 19th, 2026 - Day of the Final)
  if NEW.login_date = '2026-07-19'::date then
    if not exists (select 1 from public.user_badges where user_id = uid and badge_key = 'final_day_login') then
      perform public.award_badge(uid, 'final_day_login');
    end if;
  end if;

  return NEW;
end;
$$;

-- Create login trigger
drop trigger if exists trigger_check_login_badges on public.user_logins;
create trigger trigger_check_login_badges
after insert on public.user_logins
for each row
execute procedure public.trigger_check_login_badges();
