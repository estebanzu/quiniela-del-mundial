-- 1. Trivia Questions Table
create table if not exists public.trivia_questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null,          -- ["opcion1","opcion2","opcion3","opcion4"]
  correct_index int not null,      -- 0-based index into options array
  trivia_date date not null unique, -- the day this question is active
  category text not null default 'general',
  created_at timestamptz not null default now()
);

-- 2. Trivia Answers Table
create table if not exists public.trivia_answers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id bigint not null references public.trivia_questions(id) on delete cascade,
  selected_index int not null,
  is_correct boolean not null default false,
  points int not null default 0,
  answered_at timestamptz not null default now()
);

-- One answer per user per question
create unique index if not exists trivia_answers_user_question_unique
  on public.trivia_answers (user_id, question_id);

-- Enable RLS
alter table public.trivia_questions enable row level security;
alter table public.trivia_answers enable row level security;

