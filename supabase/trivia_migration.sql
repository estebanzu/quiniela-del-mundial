-- UPDATE: get_leaderboard to include trivia points
-- ==========================================
create or replace function public.get_leaderboard()
returns table(username text, total_points bigint, predictions_count bigint)
language plpgsql
security definer
as $$
declare
  curr_phase int;
begin
  -- Determine current active phase based on first pending match
  select 
    case 
      when min(id) is null then 6
      when min(id) <= 72 then 1
      when min(id) <= 88 then 2
      when min(id) <= 96 then 3
      when min(id) <= 100 then 4
      when min(id) <= 102 then 5
      else 6
    end into curr_phase
  from public.matches
  where status != 'finished';

  if curr_phase is null then
    curr_phase := 6;
  end if;

  return query
  select
    split_part(u.email, '@', 1)::text as username,
    (
      coalesce(sum(case 
        when curr_phase = 1 and p.match_id >= 1 and p.match_id <= 72 then p.points
        when curr_phase = 2 and p.match_id >= 73 and p.match_id <= 88 then p.points
        when curr_phase = 3 and p.match_id >= 89 and p.match_id <= 96 then p.points
        when curr_phase = 4 and p.match_id >= 97 and p.match_id <= 100 then p.points
        when curr_phase = 5 and p.match_id >= 101 and p.match_id <= 102 then p.points
        when curr_phase = 6 and p.match_id >= 103 and p.match_id <= 104 then p.points
        else 0
      end), 0) + coalesce(t.trivia_pts, 0)
    )::bigint as total_points,
    sum(case 
      when curr_phase = 1 and p.match_id >= 1 and p.match_id <= 72 then 1
      when curr_phase = 2 and p.match_id >= 73 and p.match_id <= 88 then 1
      when curr_phase = 3 and p.match_id >= 89 and p.match_id <= 96 then 1
      when curr_phase = 4 and p.match_id >= 97 and p.match_id <= 100 then 1
      when curr_phase = 5 and p.match_id >= 101 and p.match_id <= 102 then 1
      when curr_phase = 6 and p.match_id >= 103 and p.match_id <= 104 then 1
      else 0
    end)::bigint as predictions_count
  from auth.users u
  left join public.predictions p on u.id = p.user_id
  left join (
    select 
      ta.user_id,
      sum(ta.points)::bigint as trivia_pts
    from public.trivia_answers ta
    inner join public.trivia_questions tq on ta.question_id = tq.id
    where 
      (curr_phase = 1 and tq.trivia_date <= '2026-06-27') or
      (curr_phase = 2 and tq.trivia_date >= '2026-06-28' and tq.trivia_date <= '2026-07-03') or
      (curr_phase = 3 and tq.trivia_date >= '2026-07-04' and tq.trivia_date <= '2026-07-07') or
      (curr_phase = 4 and tq.trivia_date >= '2026-07-08' and tq.trivia_date <= '2026-07-12') or
      (curr_phase = 5 and tq.trivia_date >= '2026-07-13' and tq.trivia_date <= '2026-07-15') or
      (curr_phase = 6 and tq.trivia_date >= '2026-07-16')
    group by ta.user_id
  ) t on u.id = t.user_id
  where u.email like '%@quiniela.local' and u.email != 'admin@quiniela.local'
  group by u.email, t.trivia_pts
  order by total_points desc, predictions_count desc, username asc;
end;
$$;

-- ==========================================
-- UPDATE: get_leaderboard_by_phase to include trivia points
-- ==========================================
create or replace function public.get_leaderboard_by_phase()
returns table(
  username text,
  fase1 bigint,
  fase2 bigint,
  fase3 bigint,
  fase4 bigint,
  fase5 bigint,
  fase6 bigint,
  total_points bigint
)
language plpgsql
security definer
as $$
begin
  return query
  select
    split_part(u.email, '@', 1)::text as username,
    (coalesce(sum(case when p.match_id >= 1 and p.match_id <= 72 then p.points else 0 end), 0) + coalesce(t.fase1_trivia, 0))::bigint as fase1,
    (coalesce(sum(case when p.match_id >= 73 and p.match_id <= 88 then p.points else 0 end), 0) + coalesce(t.fase2_trivia, 0))::bigint as fase2,
    (coalesce(sum(case when p.match_id >= 89 and p.match_id <= 96 then p.points else 0 end), 0) + coalesce(t.fase3_trivia, 0))::bigint as fase3,
    (coalesce(sum(case when p.match_id >= 97 and p.match_id <= 100 then p.points else 0 end), 0) + coalesce(t.fase4_trivia, 0))::bigint as fase4,
    (coalesce(sum(case when p.match_id >= 101 and p.match_id <= 102 then p.points else 0 end), 0) + coalesce(t.fase5_trivia, 0))::bigint as fase5,
    (coalesce(sum(case when p.match_id >= 103 and p.match_id <= 104 then p.points else 0 end), 0) + coalesce(t.fase6_trivia, 0))::bigint as fase6,
    (coalesce(sum(p.points), 0) + coalesce(t.total_trivia, 0))::bigint as total_points
  from auth.users u
  left join public.predictions p on u.id = p.user_id
  left join (
    select
      ta.user_id,
      coalesce(sum(case when tq.trivia_date <= '2026-06-27' then ta.points else 0 end), 0)::bigint as fase1_trivia,
      coalesce(sum(case when tq.trivia_date >= '2026-06-28' and tq.trivia_date <= '2026-07-03' then ta.points else 0 end), 0)::bigint as fase2_trivia,
      coalesce(sum(case when tq.trivia_date >= '2026-07-04' and tq.trivia_date <= '2026-07-07' then ta.points else 0 end), 0)::bigint as fase3_trivia,
      coalesce(sum(case when tq.trivia_date >= '2026-07-08' and tq.trivia_date <= '2026-07-12' then ta.points else 0 end), 0)::bigint as fase4_trivia,
      coalesce(sum(case when tq.trivia_date >= '2026-07-13' and tq.trivia_date <= '2026-07-15' then ta.points else 0 end), 0)::bigint as fase5_trivia,
      coalesce(sum(case when tq.trivia_date >= '2026-07-16' then ta.points else 0 end), 0)::bigint as fase6_trivia,
      coalesce(sum(ta.points), 0)::bigint as total_trivia
    from public.trivia_answers ta
    inner join public.trivia_questions tq on ta.question_id = tq.id
    group by ta.user_id
  ) t on u.id = t.user_id
  where u.email like '%@quiniela.local' and u.email != 'admin@quiniela.local'
  group by u.email, t.fase1_trivia, t.fase2_trivia, t.fase3_trivia, t.fase4_trivia, t.fase5_trivia, t.fase6_trivia, t.total_trivia
  order by total_points desc, username asc;
end;
$$;

