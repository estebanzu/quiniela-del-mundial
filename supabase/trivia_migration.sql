-- ==========================================
-- RPC: get_today_trivia
-- Returns today's question. If the user already answered, includes their answer.
-- Never exposes correct_index before the user has answered.
-- ==========================================
create or replace function public.get_today_trivia()
returns jsonb
language plpgsql
security definer
as $$
declare
  q_record record;
  a_record record;
  result jsonb;
begin
  -- Get today's question (Costa Rica timezone = UTC-6)
  select * into q_record
  from public.trivia_questions
  where trivia_date = (now() at time zone 'America/Costa_Rica')::date;

  if q_record is null then
    return jsonb_build_object('status', 'no_question');
  end if;

  -- Check if the current user already answered
  select * into a_record
  from public.trivia_answers
  where user_id = auth.uid()
    and question_id = q_record.id;

  if a_record is not null then
    -- Already answered: include correct_index so UI can show result
    result := jsonb_build_object(
      'status', 'answered',
      'question_id', q_record.id,
      'question', q_record.question,
      'options', q_record.options,
      'category', q_record.category,
      'correct_index', q_record.correct_index,
      'selected_index', a_record.selected_index,
      'is_correct', a_record.is_correct,
      'points', a_record.points
    );
  else
    -- Not answered yet: hide the correct answer
    result := jsonb_build_object(
      'status', 'unanswered',
      'question_id', q_record.id,
      'question', q_record.question,
      'options', q_record.options,
      'category', q_record.category
    );
  end if;

  return result;
end;
$$;

-- ==========================================
-- RPC: submit_trivia_answer
-- Validates, scores (2 pts for correct), prevents double-submit.
-- ==========================================
create or replace function public.submit_trivia_answer(
  p_question_id bigint,
  p_selected_index int
)
returns jsonb
language plpgsql
security definer
as $$
declare
  q_record record;
  correct boolean;
  pts int;
  existing_id bigint;
begin
  -- Verify the question exists and is today's question
  select * into q_record
  from public.trivia_questions
  where id = p_question_id
    and trivia_date = (now() at time zone 'America/Costa_Rica')::date;

  if q_record is null then
    return jsonb_build_object('error', 'Pregunta no válida o no es la del día de hoy.');
  end if;

  -- Check if already answered
  select id into existing_id
  from public.trivia_answers
  where user_id = auth.uid()
    and question_id = p_question_id;

  if existing_id is not null then
    return jsonb_build_object('error', 'Ya respondiste esta pregunta.');
  end if;

  -- Validate selected_index
  if p_selected_index < 0 or p_selected_index >= jsonb_array_length(q_record.options) then
    return jsonb_build_object('error', 'Opción no válida.');
  end if;

  -- Score it
  correct := (p_selected_index = q_record.correct_index);
  pts := case when correct then 2 else 0 end;

  -- Insert answer
  insert into public.trivia_answers (user_id, question_id, selected_index, is_correct, points)
  values (auth.uid(), p_question_id, p_selected_index, correct, pts);

  return jsonb_build_object(
    'status', 'ok',
    'is_correct', correct,
    'correct_index', q_record.correct_index,
    'points', pts
  );
end;
$$;

-- ==========================================
-- RPC: get_trivia_stats
-- Returns trivia stats for the current user.
-- ==========================================
create or replace function public.get_trivia_stats()
returns jsonb
language plpgsql
security definer
as $$
declare
  total_answered int;
  total_correct int;
  total_pts bigint;
  current_streak int;
  a_rec record;
begin
  select
    count(*)::int,
    count(*) filter (where is_correct)::int,
    coalesce(sum(points), 0)::bigint
  into total_answered, total_correct, total_pts
  from public.trivia_answers
  where user_id = auth.uid();

  -- Calculate current streak (consecutive correct answers, most recent first)
  current_streak := 0;
  for a_rec in
    select ta.is_correct
    from public.trivia_answers ta
    inner join public.trivia_questions tq on tq.id = ta.question_id
    where ta.user_id = auth.uid()
    order by tq.trivia_date desc
  loop
    if a_rec.is_correct then
      current_streak := current_streak + 1;
    else
      exit;
    end if;
  end loop;

  return jsonb_build_object(
    'total_answered', total_answered,
    'total_correct', total_correct,
    'total_points', total_pts,
    'current_streak', current_streak
  );
end;
$$;

